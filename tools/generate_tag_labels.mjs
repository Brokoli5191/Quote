// Offline build-time script (NOT shipped in the app).
// Generates app/src/main/java/app/brokoli5191/quote/data/TagLabels.kt from tools/tag_vocabulary.json
// so the app can show the curated quote tags in German.
//
// Usage: node tools/generate_tag_labels.mjs [--check]
//   --check  exit 1 if TagLabels.kt is out of date, write nothing
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.dirname(fileURLToPath(import.meta.url));
const vocabularyPath = path.join(toolsDir, 'tag_vocabulary.json');
const outPath = path.join(toolsDir, '..', 'app', 'src', 'main', 'java', 'app', 'brokoli5191', 'quote', 'data', 'TagLabels.kt');

const vocabulary = JSON.parse(fs.readFileSync(vocabularyPath, 'utf8'));
const kotlinString = (value) => JSON.stringify(value).replace(/\$/g, '\\$');
const entries = vocabulary.map((entry) => `    ${kotlinString(entry.en)} to ${kotlinString(entry.de)},`);

const source = `package app.brokoli5191.quote.data

// Generated by tools/generate_tag_labels.mjs from tools/tag_vocabulary.json. Do not edit by hand.

private val germanTagLabels: Map<String, String> = mapOf(
${entries.join('\n')}
)

/** Display label for a quote tag: the German label for "de", otherwise the slug with spaces. */
fun tagLabel(tag: String, language: String): String {
    val slug = tag.trim()
    if (language == QuoteLanguage.GERMAN) germanTagLabels[slug.lowercase()]?.let { return it }
    return slug.replace('-', ' ')
}

/** True for tags from the curated vocabulary; older seeds also carried noisy source tags. */
fun isVocabularyTag(tag: String): Boolean = tag.trim().lowercase() in germanTagLabels
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (current !== source) {
    console.error('TagLabels.kt is out of date; run node tools/generate_tag_labels.mjs');
    process.exit(1);
  }
  console.log(`TagLabels.kt is up to date (${vocabulary.length} tags).`);
} else {
  fs.writeFileSync(outPath, source);
  console.log(`Wrote ${vocabulary.length} tag labels to ${path.relative(process.cwd(), outPath)}`);
}
